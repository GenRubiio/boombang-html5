test.describe('registry-mismatch reporting (design.md §7)', () => {
  test.beforeEach(async ({ page }) => {
    await page.goto('/harness.html')
    await page.waitForFunction(() => !!window.__avatarHarness)
  })

  test('an unregistered accessory is never silently created', async ({ page }) => {
    const socketId = `rasta_mismatch_${Date.now()}_${socketCounter++}`
    await page.evaluate(
      ({ socketId }) =>
        window.__avatarHarness.spawnAvatar({
          socketId,
          avatarId: 12,
          accessories: { hat: 'totallyUnknownHat', pet: 'totallyUnknownPet' },
        }),
      { socketId }
    )
    const state = await page.evaluate(
      ({ socketId }) => {
        window.__avatarHarness.setDirection(socketId, 'down')
        return window.__avatarHarness.readState(socketId)
      },
      { socketId }
    )
    const kinds = state.children.map((c) => c.kind)

    // No accessory child was created for either uncompiled/unregistered key — the container is
    // exactly {shadow, body, nameBackground, nameText}, never a placeholder or a crash.
    expect(kinds).toEqual(['shadow', 'body', 'nameBackground', 'nameText'])
  })
})

// Live-caught defect (tasks.md slices 28-31, apply-progress.md): `buildAccessoryPackagesFromGlob`
// used to overwrite (not accumulate) the `webp` role per registry key, so a multi-page accessory
// package (any hat needing >1 page — measured for real across the batch compile: most hats at 2
// pages, `rasta`'s own `pineappleHat` at 2) kept only ONE page's loader, and
// `AccessoryManager.load()` then patched EVERY atlas texture entry to that SAME single webp URL
// — page 1+'s frames would render page 0's pixel data cropped at the wrong coordinates. Fixed by
// making `webp` always an array (one loader per page, sorted so index matches page order,
// mirroring the body's own already-correct `groupLayeredActionKeyLoaders.js` precedent) and
// patching each atlas texture entry to ITS OWN page's URL by index.
test.describe('multi-page accessory loading (tasks.md slices 28-31 defect fix)', () => {
  test.beforeEach(async ({ page }) => {
    await page.goto('/harness.html')
    await page.waitForFunction(() => !!window.__avatarHarness)
  })

  // Fixture reassigned (accessory ss:1 rule, 2026-08-19): `rasta/pineappleHat` was 2 pages when
  // this test was written (slice 28) but is one of the 249 hats the whole-package ss:1 rule
  // recompiled — halving raster density shrank it to a single page, an expected, measured
  // consequence (see apply-progress.md's accessory ss:1 section), not a regression. Every one of
  // rasta's own 36 accessory packages is now 1 page (confirmed live), so no rasta fixture can
  // exercise this test's actual subject (distinct-image-data-per-page) any more; `boomer/mickeyHat`
  // is a REAL, currently-2-page package (confirmed live, unaffected by ss:1 since it stayed under
  // budget) that exercises the identical code path.
  test('a 2-page hat (boomer/mickeyHat) loads DISTINCT image data per page, not the same page repeated', async ({
    page,
  }) => {
    const socketId = `boomer_multipage_${Date.now()}_${socketCounter++}`
    await page.evaluate(
      ({ socketId }) =>
        window.__avatarHarness.spawnAvatar({
          socketId,
          avatarId: 1,
          accessories: { hat: 'mickeyHat' },
        }),
      { socketId }
    )
    await page.evaluate(({ socketId }) => window.__avatarHarness.setDirection(socketId, 'down'), {
      socketId,
    })

    const result = await page.evaluate(() => {
      const texture = window.game.textures.get('acc_boomer_hat_mickeyHat_atlas')
      return {
        pageCount: texture.source.length,
        // Each TextureSource's own `image.src` is the Blob object URL
        // `AccessoryManager.load()` patched onto that page's `atlas.json` frame group — distinct
        // per page after the fix, all identical (the defect) before it.
        sources: texture.source.map((s) => s.image.src),
      }
    })

    expect(result.pageCount, 'boomer/mickeyHat is compiled to 2 pages (measured live, 2026-08-19)').toBe(2)
    expect(new Set(result.sources).size, 'each page must load its OWN distinct image data').toBe(
      result.pageCount
    )
  })
})
