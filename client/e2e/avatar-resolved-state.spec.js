    test('R8-pixel: the ACTUAL RENDERED PIXEL colour of a body slot matches the resolved palette, not merely the logical child.tint property', async ({
      page,
    }) => {
      // Coordinator-flagged defect (recorded in apply-progress.md): every prior assertion in
      // this file that checks a colour reads `child.tint` (a Phaser Sprite property Phaser
      // updates the moment `setTint()` is called), which is exactly the wiring-not-outcome gap
      // design.md §19 risk 18 names. `child.tint` is set correctly REGARDLESS of whether the
      // active renderer ever draws it — confirmed live: under `Phaser.CANVAS`, `setTint()`
      // updated `.tint` to the resolved colour while the actual rendered pixel stayed pure
      // white, because `Phaser.Renderer.Canvas.CanvasRenderer#batchSprite` draws every sprite
      // via a plain `ctx.drawImage(...)` with no tint handling at all. This test reads a REAL
      // screenshot pixel instead, so it fails exactly where every `.tint`-only assertion above
      // (including R8 itself) did not.
      const socketId = await spawnCharacter(page, {
        // {x:5, y:5} tile position (same trick `buildAvatarContactSheet.js` documents): the
        // numeric matrix's default {x:0, y:0} spawn renders with its feet at the very top edge
        // of the canvas, entirely off-screen — harmless for every OTHER test above, which reads
        // resolved logical state only, but this is the first test in this file that needs the
        // avatar to be actually ON the visible canvas to sample a real pixel from it.
        x: 5,
        y: 5,
        palette: { [pixelCheckSlot]: pixelCheckColor },
      })

      const manifestHasSlot = await page.evaluate(
        ({ socketId, slot }) =>
          // Correction 2 (apply-progress.md, 2026-08-18): checking `defaults` alone conflates
          // "no manifest default value" with "no palette slot at all" — `computeManifestSlots`'s
          // union (tasks.md slice 26 defect 2) means a character with an empty vector colormeta
          // (ninja/werewolf/skeleton/zombie) can still have a REAL piece-referenced slot in
          // `manifest.slots` that `resolvePalette` (which iterates `manifest.slots`, not
          // `defaults`) honours. `manifest.slots` is the correct membership check.
          window.game.scene.getScenes(true)[0].users[socketId].spriteAvatar._manifest.slots.includes(slot),
        { socketId, slot: pixelCheckSlot }
      )
      test.skip(!manifestHasSlot, `${character}'s manifest has no "${pixelCheckSlot}" slot`)

      const rect = await page.evaluate(
        ({ socketId, slot }) => {
          window.__avatarHarness.setDirection(socketId, 'down')
          const scene = window.game.scene.getScenes(true)[0]
          const avatar = scene.users[socketId].spriteAvatar
          const candidates = avatar._pool.filter((child) => {
            if (!child.visible) return false
            const pieceId = child.getData('pieceId')
            const manifestPiece = pieceId && avatar._manifest.pieces[pieceId]
            return manifestPiece && manifestPiece.slot === slot
          })
          if (candidates.length === 0) return null
          // Live-discovered (tasks.md slice 21 defect-1 fix): a slotted run's bounding box is
          // NOT necessarily uniformly filled — the FIRST match can be a small, irregularly
          // shaped run (an eyebrow, a fingernail) whose geometric centre lands on a
          // partially-transparent/anti-aliased pixel, blending with whatever sits behind it and
          // producing a flaky, non-representative sample. The LARGEST-by-area candidate (e.g.
          // rasta's own face/torso run) is overwhelmingly likely to have a solid, uniformly
          // coloured interior at its own centre.
          const biggest = candidates.reduce((best, child) => {
            const b = child.getBounds()
            const area = b.width * b.height
            return !best || area > best.area ? { child, area, bounds: b } : best
          }, null)
          const bounds = biggest.bounds
          const canvasRect = document.querySelector('canvas').getBoundingClientRect()
          return {
            // page-space clip: the piece's own world-space bounds (== canvas-local, this
            // harness's camera never scrolls) offset by the canvas element's own page position.
            x: canvasRect.left + bounds.left,
            y: canvasRect.top + bounds.top,
            width: bounds.width,
            height: bounds.height,
          }
        },
        { socketId, slot: pixelCheckSlot }
      )
      expect(rect, `${character} has a visible "${pixelCheckSlot}"-slotted piece`).toBeTruthy()

      // Real paint wait (matching avatar-contact-sheet.spec.js's own documented need) — this is
      // the first assertion in THIS file that reads an actual rendered pixel, not resolved
      // logical state.
      await page.waitForTimeout(100)

      // Sample a small patch well inside the piece's own bounds (avoids anti-aliased edge
      // pixels, which legitimately blend with whatever sits behind them).
      const maxSampleSize = Math.max(2, Math.min(8, Math.floor(Math.min(rect.width, rect.height) / 2)))

      // tasks.md slice 24 live finding: the geometric bbox CENTRE of "the biggest same-slot
      // run" is not reliably interior-filled across the roster the way it is for rasta/sally/
      // cholo — brujita's biggest `color1` ("piel") run's bbox centre lands under her hat brim
      // (sampled near-black, not skin), and empollon's/gata's land in the transparent gap
      // between two disjoint skin regions the run's own bbox spans (both hands, or face+neck
      // with a gap) — confirmed live via direct pixel probes, not assumed. The run's bbox is
      // still the right SEARCH AREA (design.md's own "largest run" heuristic remains correct:
      // it is overwhelmingly likely to CONTAIN a solid interior patch somewhere), but the exact
      // centre is not reliably THAT patch for every character's art. Search a small, fixed grid
      // of candidate points across the run's own bbox (never expanding the search outside it)
      // and keep the SINGLE candidate with the lowest differing fraction — this still requires
      // one genuine solid-coloured match against the resolved palette (the real defect this
      // test exists to catch, 100% differing, fails at every candidate identically), it just
      // stops assuming the bbox centre is always that match.
      //
      // tasks.md slice 26 live finding: `yayo`'s own biggest `color1` run is a genuinely
      // NARROW visible strip (the nose bridge between two large sunglasses lenses — most of
      // the run's own bbox is covered by the sunglasses/moustache pieces drawn on top, both
      // unrelated to `color1`) — narrower than an 8x8 patch anywhere within it, so even the
      // best of the 25 fixed-size candidates above still straddled the sunglasses' dark rim.
      // Shrinking the sample size (4x4, then 2x2) over the SAME grid, only once the largest
      // size fails to find a clean match, finds a genuinely interior point without widening the
      // search area or lowering the match threshold.
      const CANDIDATE_FRACTIONS = [0.2, 0.35, 0.5, 0.65, 0.8]
      let best = null
      sizes: for (const sampleSize of [maxSampleSize, 4, 2]) {
        if (sampleSize > maxSampleSize) continue
        for (const yFraction of CANDIDATE_FRACTIONS) {
          for (const xFraction of CANDIDATE_FRACTIONS) {
            const clip = {
              x: Math.round(rect.x + rect.width * xFraction - sampleSize / 2),
              y: Math.round(rect.y + rect.height * yFraction - sampleSize / 2),
              width: sampleSize,
              height: sampleSize,
            }
            const screenshotBuffer = await page.screenshot({ clip })
            // `.ensureAlpha()`: a Playwright screenshot PNG has no alpha channel (opaque
            // background), so a raw decode without it is 3-channel RGB — `diffRgbaBuffers`
            // requires 4 (RGBA), the same shape `buildSolidRgbaBuffer` always produces.
            const { data: sampledRgba } = await sharp(screenshotBuffer)
              .ensureAlpha()
              .raw()
              .toBuffer({ resolveWithObject: true })

            const expectedRgba = buildSolidRgbaBuffer(sampleSize, sampleSize, pixelCheckColor)
            // Reuses the already-tested R16/R17b comparator (shared/assetPipeline/compareRasters.js)
            // rather than writing a second pixel-diff routine. Tolerance 40 per channel: generous
            // enough for WebGL compositing/anti-aliasing rounding on a real screenshot, nowhere
            // near enough to let a pure-white (255,255,255) rendered patch pass against a
            // resolved skin/costume colour — every one of rasta's own `colormeta.defaults`
            // values differs from white by well over 100 on at least one channel (e.g. color1
            // `b88a5c`: |0xb8-0xff|=71).
            const { differingPixels, totalPixels } = diffRgbaBuffers(
              new Uint8ClampedArray(sampledRgba),
              expectedRgba,
              sampleSize,
              sampleSize,
              { tolerance: 40 }
            )
            const differingFraction = differingPixels / totalPixels
            if (!best || differingFraction < best.differingFraction) {
              best = { differingFraction, totalPixels, xFraction, yFraction, sampleSize }
            }
            if (differingFraction === 0) break sizes // already found a perfect interior match
          }
        }
        if (best && best.differingFraction <= 0.1) break // good enough at this size already
      }

      // Live-discovered (tasks.md slice 21 defect-1 fix): even the LARGEST slotted run is not
      // a perfect rectangle at pixel scale — a handful of pixels at the very centre-row/column
      // of an 8x8 sample can still land on a genuinely anti-aliased sub-pixel edge (confirmed:
      // 5/64 differing pixels on rasta's own biggest color1 run, all consistent with edge
      // blending, none anywhere close to the 64/64-differing signature the real CANVAS-renderer
      // defect produced). A MAJORITY threshold (≥90% of the BEST candidate sample must match) is
      // what actually distinguishes "correctly tinted, minor edge anti-aliasing" from "not
      // tinted at all" — asserting a literal 0 here would be exact-pixel-baseline brittleness of
      // the kind this change deliberately rejected elsewhere (design.md's own resolved-state-
      // over-baseline choice), while a majority-match threshold still fails hard against the
      // real defect (which produced 100% differing at EVERY candidate point, not a handful of
      // edge pixels at only one of them).
      expect(
        best.differingFraction,
        `no candidate patch (sizes up to ${maxSampleSize}x${maxSampleSize}, ${CANDIDATE_FRACTIONS.length}x${CANDIDATE_FRACTIONS.length} grid each) at a "${pixelCheckSlot}" piece rendered close to ${pixelCheckColor} (best: ${best.differingFraction} at ${best.sampleSize}x${best.sampleSize})`
      ).toBeLessThanOrEqual(0.1)
      expect(best.totalPixels).toBe(best.sampleSize * best.sampleSize)
    })

